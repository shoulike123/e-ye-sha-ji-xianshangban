def set_run_font(run, name="微软雅黑", size=11, bold=False, color=None):
    run.bold = bold
    run.font.size = Pt(size)
    run.font.name = name
    run._element.rPr.rFonts.set(qn("w:eastAsia"), name)
    if color:
        run.font.color.rgb = RGBColor(*color)


def add_p(doc, text, *, size=11, bold=False, color=None, space_after=6, first_line=False):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.space_before = Pt(0)
    p.paragraph_format.line_spacing = 1.35
    if first_line:
        p.paragraph_format.first_line_indent = Cm(0.74)
    run = p.add_run(text)
    set_run_font(run, size=size, bold=bold, color=color)
    return p


def add_heading_cn(doc, text, level=1):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(16 if level == 1 else 12)
    p.paragraph_format.space_after = Pt(8)
    sizes = {1: 16, 2: 14, 3: 12}
    colors = {1: (0x1A, 0x1A, 0x1A), 2: (0x33, 0x33, 0x33), 3: (0x44, 0x44, 0x44)}
    run = p.add_run(text)
    set_run_font(run, size=sizes.get(level, 12), bold=True, color=colors.get(level))
    return p


def add_q(doc, n, title, lines):
    add_heading_cn(doc, f"疑问 {n}　{title}", 3)
    for line in lines:
        add_p(doc, line, first_line=False)


def set_cell(cell, text, *, bold=False, fill=None):
    cell.text = ""
    p = cell.paragraphs[0]
    p.paragraph_format.space_after = Pt(2)
    p.paragraph_format.space_before = Pt(2)
    run = p.add_run(text)
    set_run_font(run, size=10, bold=bold)
    if fill:
        tc = cell._tc
        tcPr = tc.get_or_add_tcPr()
        shd = tcPr.makeelement(
            qn("w:shd"),
            {
                qn("w:val"): "clear",
                qn("w:color"): "auto",
                qn("w:fill"): fill,
            },
        )
        tcPr.append(shd)


def add_table(doc, headers, rows):
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.style = "Table Grid"
    table.autofit = True
    for i, h in enumerate(headers):
        set_cell(table.rows[0].cells[i], h, bold=True, fill="E8E8E8")
    for r, row in enumerate(rows):
        for c, val in enumerate(row):
            set_cell(table.rows[r + 1].cells[c], val)
    doc.add_paragraph().paragraph_format.space_after = Pt(4)
    return table


